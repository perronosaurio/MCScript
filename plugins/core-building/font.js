const WIDTH = 5
const HEIGHT = 7
const SPACE_WIDTH = 3

const parsed = Object.fromEntries(Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split(' ')]))

function glyph (ch) {
  if (parsed[ch]) return parsed[ch]
  const base = ch.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase()
  return parsed[base] || null
}

// Returns the filled pixels of a text as [x, y] pairs (y = 0 at the bottom row)
function layout (text) {
  const pixels = []
  let cursor = 0
  for (const ch of text) {
    if (ch === ' ') { cursor += SPACE_WIDTH + 1; continue }
    const rows = glyph(ch)
    if (!rows) { cursor += SPACE_WIDTH + 1; continue }
    rows.forEach((row, r) => {
      for (let c = 0; c < WIDTH; c++) if (row[c] === '1') pixels.push([cursor + c, HEIGHT - 1 - r])
    })
    cursor += WIDTH + 1
  }
  return { pixels, width: Math.max(0, cursor - 1), height: HEIGHT }
}

